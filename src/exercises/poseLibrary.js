/**
 * Returns the complete 15-pose progressive sequence ordered Level 1 -> Level 2 -> Level 3,
 * or filters to a specific level when requested.
 */
export function selectArcadeRoundPoses(levelFilter = 'All') {
  if (POSE_DIFFICULTIES.includes(levelFilter)) {
    return POSE_LIBRARY.filter((p) => p.levelName === levelFilter || p.difficulty === levelFilter);
  }
  return [...POSE_LIBRARY];
}
